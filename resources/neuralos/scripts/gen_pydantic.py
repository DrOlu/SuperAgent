#!/usr/bin/env python3
"""Generate strict Pydantic v2 models from a neuralos profile.

Reads profile.json (emitted by profile_data.py) and writes models.py with one
model per table (databases) or per record shape (files / log templates). Every
field carries constraints derived from observed data: ranges from min/max,
patterns from log templates, Literal unions from low-cardinality strings,
Optional where nulls occur, and datetime parsing validators.

Usage:
  python gen_pydantic.py --profile profile.json --out models.py [--table NAME] [--model-name Transaction]
"""

import argparse
import os
import json
import re
from datetime import datetime, timezone

